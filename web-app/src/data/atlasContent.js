// Photographie prête à l'emploi : sources, dimensions proposées et crédit.
// null lorsqu'aucune photographie libre n'est disponible.
export function atlasPhoto(key) {
  if (!CREDITS[key]) return null
  const [author, license, source] = CREDITS[key]
  const full = file(`${key}-full`)
  return {
    src: full,
    thumb: file(`${key}-480`),
    srcSet: `${file(`${key}-480`)} 480w, ${full} 1280w`,
    author,
    license,
    sourceUrl: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(source)}`,
  }
}

